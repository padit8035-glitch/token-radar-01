// Token radar, model radar-2: the snapshot in, a ranked board out.
//
// The board covers every protocol the rule admits: the 40 on the watchlist plus
// every other pre-token protocol below the floor that is not an exchange, not a
// versioned pool and not a wrapped, staked or bridged product. Live-token
// protocols are kept apart and shown with the market's own values.
//
// Implied value follows only from the snapshot's own figures, in five factors:
//
//   multiple   the market's own price for a token like this one: the median
//              market-cap-to-TVL of the live-token protocols in the same
//              category, shrunk toward the global median where a category
//              has few live protocols, clamped to [0.05, 1.00]
//   growth     1 + clamp(change_7d, -60, 120) / 100 * 0.5
//   maturity   0.6 + min(age_days, 1095) / 1095 * 0.4 (age unknown: 365)
//   breadth    1 + 0.05 * min(chains - 1, 4), at most 1.20
//   certainty  0.95 when the snapshot reports no 7-day change, else 1
//   implied    max(1, round(tvl_usd * multiple * growth * maturity * breadth * certainty))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the dashboard shows each row's five factors so a reader can check the
// arithmetic. A protocol is said to record no token, never to have none:
// DefiLlama's record is not proof.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

